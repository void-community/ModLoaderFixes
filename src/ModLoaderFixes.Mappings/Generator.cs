namespace ModLoaderFixes.Mappings;

/// <summary>Resolves the requested classes in every release they were requested in and writes them as <c>Mappings.g.cs</c>.</summary>
internal static class Generator
{
    /// <summary>Resolves the requests from the real mappings, which it keeps in a cache between builds, and writes the table's text.</summary>
    /// <param name="requests">The requests that the agent's build writes from its <c>MappedClass</c> items.</param>
    /// <param name="cache">The directory that keeps the downloaded mapping files.</param>
    /// <param name="client">The client that downloads the mappings.</param>
    /// <param name="cancellationToken">Cancels the downloads.</param>
    /// <returns>The table.</returns>
    internal static async Task<string> GenerateAsync(string requests, string cache, HttpClient client, CancellationToken cancellationToken)
    {
        MappingSources sources = await MappingSources.CreateAsync(client, cache, cancellationToken)
            .ConfigureAwait(continueOnCapturedContext: false);

        IReadOnlyList<ResolvedClass> classes = await ResolveAsync(ClassRequest.Parse(requests), sources, cancellationToken).ConfigureAwait(continueOnCapturedContext: false);

        return Write(classes);
    }

    /// <summary>Names releases, a run of consecutive ones by its ends: <c>1.7.6 to 1.7.10</c>.</summary>
    /// <param name="versions">The releases to name.</param>
    /// <param name="releases">Every release that was requested, in order, which tells the runs apart.</param>
    /// <returns>The text.</returns>
    internal static string Label(IReadOnlyList<string> versions, IReadOnlyList<string> releases)
    {
        ArgumentNullException.ThrowIfNull(versions);
        ArgumentNullException.ThrowIfNull(releases);

        List<string> runs = [];
        int[] indices = [.. versions.Select(version => Resolver.IndexOf(releases, version)).Order()];

        for (int start = 0; start < indices.Length;)
        {
            int end = start;

            while (end + 1 < indices.Length && indices[end + 1] == indices[end] + 1)
                end++;

            string first = releases[indices[start]];
            string last = releases[indices[end]];

            runs.Add((end - start) switch { 0 => first, 1 => first + " and " + last, _ => first + " to " + last, });

            start = end + 1;
        }

        return string.Join(separator: ", ", runs);
    }

    /// <summary>
    /// Resolves each requested class in every release it is requested in, by the names Forge runs those releases under. It goes release by release, and in each
    /// resolves every class requested there, so that the sources need only the few mappings of one release at a time.
    /// </summary>
    /// <param name="requests">The classes and the releases to find each in.</param>
    /// <param name="sources">The mappings of each release.</param>
    /// <param name="cancellationToken">Cancels the downloads.</param>
    /// <returns>The classes, in the order of the requests.</returns>
    internal static async Task<IReadOnlyList<ResolvedClass>> ResolveAsync(IReadOnlyList<ClassRequest> requests, IMappingSources sources, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(requests);
        ArgumentNullException.ThrowIfNull(sources);

        Resolver resolver = new(sources);
        IReadOnlyList<string> releases = sources.Releases;
        RequestedClass[] classes = [.. requests.Select(request => Requested(request, releases))];

        for (int index = 0; index < releases.Count; index++)
        {
            foreach (RequestedClass requested in classes.Where(requested => requested.From <= index && index <= requested.To))
            {
                ClassRequest request = requested.Request;

                Resolution resolution = await resolver.ResolveAsync(request.Names, request, releases[index], cancellationToken)
                    .ConfigureAwait(continueOnCapturedContext: false);

                requested.Add(releases[index], resolution.Naming);
            }
        }

        return [.. classes.Select(static requested => requested.Resolved())];
    }

    /// <summary>Writes the table: one <c>MappedClass</c> property per requested class.</summary>
    /// <param name="classes">The resolved classes, in the order to write them.</param>
    /// <returns>The table's text.</returns>
    internal static string Write(IReadOnlyList<ResolvedClass> classes)
    {
        ArgumentNullException.ThrowIfNull(classes);

        List<string> lines =
        [
            "// <auto-generated>",
            "// src/ModLoaderFixes.Mappings generated this as the agent built, from its MappedClass items.",
            "// </auto-generated>",
            "",
            "namespace ModLoaderFixes;",
            "",
            "/// <summary>The classes that the patches name, with the names that each vanilla release gives them and the methods the patches name.</summary>",
            "internal static class MappedClasses",
            "{",
        ];

        foreach (ResolvedClass resolved in classes)
        {
            ClassRequest request = resolved.Request;

            if (lines[^1] != "{")
                lines.Add(item: "");

            // The property, with the release range it covers in its documentation.
            lines.Add("    /// <summary>Gets <c>" + request.Name + "</c> in Minecraft " + request.From + " to " + request.To + ".</summary>");
            lines.Add("    internal static MappedClass " + request.Property + " { get; } = new(");

            // The names that Forge runs the class and its methods under.
            lines.Add("        name: " + Quote(request.Name) + ",");
            lines.Add("        methods: " + Methods(request.Methods) + ",");

            // The names of each vanilla naming, with the releases that share it.
            lines.Add(item: "        vanilla:");
            lines.Add(item: "        [");

            lines.AddRange(resolved.Namings
                .Select(static naming => "            (" + Quote(naming.Versions) + ", " + Quote(naming.Naming.Name) + ", " + Methods(naming.Naming.Methods) + "),"));

            lines.Add(item: "        ]");
            lines.Add(item: "    );");
        }

        lines.Add(item: "}");

        return string.Join(separator: '\n', lines) + "\n";
    }

    private static string Methods(IEnumerable<MethodName> methods)
    {
        return "[" + string.Join(separator: ", ",
            methods.Select(static method => "(" + Quote(method.Name) + ", " + Quote(method.Descriptor) + ")")) + "]";
    }

    private static string Quote(string value)
    {
        return "\"" + value + "\"";
    }

    private static RequestedClass Requested(ClassRequest request, IReadOnlyList<string> releases)
    {
        int from = Resolver.IndexOf(releases, request.From);
        int to = Resolver.IndexOf(releases, request.To);

        return to < from
            ? throw new InvalidOperationException(request.Name + " is requested from " + request.From + ", which comes after " + request.To + ".")
            : ClassRequest.NamesOf(request.From) != ClassRequest.NamesOf(request.To)
                ? throw new InvalidOperationException(request.Name + " is requested from " + request.From + " to " + request.To + ", across Forge's change of names in 1.17.")
                : new RequestedClass(request, from, to, versions: [.. releases.Skip(from).Take(to - from + 1)]);
    }

    // A request with the places of its first and last release among the releases, and the namings found for it so far, each with the releases that share it.
    private sealed class RequestedClass(ClassRequest request, int from, int to, string[] versions)
    {
        private readonly List<Naming> _namings = [];
        private readonly List<List<string>> _shared = [];

        internal int From => from;
        internal ClassRequest Request => request;
        internal int To => to;

        internal void Add(string version, Naming naming)
        {
            int existing = _namings.FindIndex(other => other.Key == naming.Key);

            if (existing < 0)
            {
                _namings.Add(naming);
                _shared.Add(item: [version]);
            }
            else
            {
                _shared[existing].Add(version);
            }
        }

        internal ResolvedClass Resolved()
        {
            return new ResolvedClass(request, Namings: [.. _namings.Select((naming, index) => new ReleaseNaming(Label(_shared[index], versions), naming))]);
        }
    }
}
